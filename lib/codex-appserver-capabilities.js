import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, realpathSync, rmSync, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { CODEX_REQUEST_USER_INPUT_METHODS } from './codex-request-user-input.js';

const cache = new Map();
const promptCache = new Map();

export function extractRequestUserInputMethods(schema) {
  const text = typeof schema === 'string' ? schema : JSON.stringify(schema || {});
  return CODEX_REQUEST_USER_INPUT_METHODS.filter(method => text.includes(`"${method}"`));
}

function acceptsString(property) {
  if (!property || typeof property !== 'object') return false;
  if (property.type === 'string') return true;
  return Array.isArray(property.type) && property.type.includes('string');
}

export function extractThreadInstructionSupport(schema) {
  const parsed = typeof schema === 'string' ? JSON.parse(schema) : schema;
  const properties = parsed?.title === 'ThreadStartParams' ? parsed.properties : null;
  return {
    append: acceptsString(properties?.developerInstructions),
    override: acceptsString(properties?.baseInstructions),
  };
}

function invocation(codexPath, args) {
  return codexPath.endsWith('.js')
    ? { command: process.execPath, args: [codexPath, ...args] }
    : { command: codexPath, args };
}

/** Verify support against the schema generated by the exact CLI binary CXV launches. */
export function inspectCodexRequestUserInputSupport(codexPath) {
  if (!codexPath) return { verified: false, version: null, methods: [], error: 'missing Codex path' };
  if (cache.has(codexPath)) return cache.get(codexPath);

  const outDir = mkdtempSync(join(tmpdir(), 'cxv-codex-schema-'));
  let result;
  try {
    const versionCall = invocation(codexPath, ['--version']);
    const version = execFileSync(versionCall.command, versionCall.args, {
      encoding: 'utf8',
      timeout: 10000,
      stdio: ['ignore', 'pipe', 'pipe'],
    }).trim();
    const schemaCall = invocation(codexPath, [
      'app-server',
      'generate-json-schema',
      '--experimental',
      '--out',
      outDir,
    ]);
    execFileSync(schemaCall.command, schemaCall.args, {
      encoding: 'utf8',
      timeout: 15000,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    const schema = readFileSync(join(outDir, 'ServerRequest.json'), 'utf8');
    const methods = extractRequestUserInputMethods(schema);
    result = {
      verified: methods.length > 0,
      version,
      methods,
      error: methods.length > 0 ? null : 'request_user_input server request absent from generated schema',
    };
  } catch (error) {
    result = {
      verified: false,
      version: null,
      methods: [],
      error: error?.message || String(error),
    };
  } finally {
    try { rmSync(outDir, { recursive: true, force: true }); } catch {}
  }
  cache.set(codexPath, result);
  return result;
}

/** Verify new-thread instruction fields against the exact binary CX Viewer launches. */
export function inspectCodexSystemPromptSupport(codexPath) {
  if (!codexPath) {
    return { verified: false, append: false, override: false, version: null, error: 'missing Codex path' };
  }
  let identity = codexPath;
  try {
    const real = realpathSync(codexPath);
    const stat = statSync(real);
    identity = `${real}:${stat.size}:${stat.mtimeMs}`;
  } catch {}
  if (promptCache.has(identity)) return promptCache.get(identity);

  const outDir = mkdtempSync(join(tmpdir(), 'cxv-codex-prompt-schema-'));
  let result;
  try {
    const versionCall = invocation(codexPath, ['--version']);
    const version = execFileSync(versionCall.command, versionCall.args, {
      encoding: 'utf8',
      timeout: 10000,
      stdio: ['ignore', 'pipe', 'pipe'],
    }).trim();
    const schemaCall = invocation(codexPath, [
      'app-server',
      'generate-json-schema',
      '--experimental',
      '--out',
      outDir,
    ]);
    execFileSync(schemaCall.command, schemaCall.args, {
      encoding: 'utf8',
      timeout: 15000,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    const support = extractThreadInstructionSupport(
      readFileSync(join(outDir, 'v2', 'ThreadStartParams.json'), 'utf8'),
    );
    result = {
      verified: support.append && support.override,
      ...support,
      version,
      error: support.append && support.override
        ? null
        : 'thread/start instruction fields absent from generated schema',
    };
  } catch (error) {
    result = {
      verified: false,
      append: false,
      override: false,
      version: null,
      error: error?.message || String(error),
    };
  } finally {
    try { rmSync(outDir, { recursive: true, force: true }); } catch {}
  }
  promptCache.set(identity, result);
  return result;
}

export function _resetCodexCapabilityCacheForTests() {
  cache.clear();
  promptCache.clear();
}
